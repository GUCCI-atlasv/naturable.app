// Pull the rule engine and word links from their sources, and render the icons.
//   RULES_DIR  naturable-rules checkout   (default: ../../naturable-rules, next to this repo)
//   SITE_DIR   the site                   (default: this repo's root, one level up)
// Output is committed, so the extension builds without the rules checkout.
import { copyFileSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright-core";
import { chromePath } from "./chrome.mjs";

const ROOT = resolve(import.meta.dirname, "..");
const RULES = resolve(ROOT, process.env.RULES_DIR || "../../naturable-rules");
const SITE = resolve(ROOT, process.env.SITE_DIR || "..");
const ORIGIN = "https://naturable.app";

// 1. Engine + packs (one IIFE, exposes Naturable). No code is ever fetched at runtime.
mkdirSync(join(ROOT, "src/vendor"), { recursive: true });
copyFileSync(join(RULES, "dist/naturable.iife.js"), join(ROOT, "src/vendor/naturable.iife.js"));
copyFileSync(join(RULES, "LICENSE"), join(ROOT, "src/vendor/LICENSE-naturable-rules"));
copyFileSync(join(RULES, "LICENSE-DATA.md"), join(ROOT, "src/vendor/LICENSE-DATA.md"));
const rulesPkg = JSON.parse(readFileSync(join(RULES, "package.json"), "utf8"));

// 2. Word-level "Learn more" anchors (delve -> /en/ai-words-to-avoid/#delve), same map the site uses.
const { DOCS } = await import(pathToFileURL(join(SITE, "src/docs.mjs")).href);
const words = Object.fromEntries(Object.entries(DOCS.words).map(([w, href]) => [w, ORIGIN + href]));
writeFileSync(
  join(ROOT, "src/shared/docs-words.js"),
  `/* Generated by scripts/sync.mjs from naturable.app src/docs.mjs. Do not edit. */\nglobalThis.NAT_WORDS = ${JSON.stringify(words)};\n`
);

// 3. Icons from the store icon (store/source/icon-128-padded.png: 96px artwork + 16px transparent padding,
//    as the Chrome Web Store asks). 128 is used as-is; toolbar sizes crop the padding so they fill the slot.
const iconSrc = "data:image/png;base64," + readFileSync(join(ROOT, "store/source/icon-128-padded.png")).toString("base64");
const browser = await chromium.launch({ executablePath: chromePath() });
const page = await browser.newPage();
mkdirSync(join(ROOT, "src/icons"), { recursive: true });
copyFileSync(join(ROOT, "store/source/icon-128-padded.png"), join(ROOT, "src/icons/128.png"));
for (const size of [16, 32, 48]) {
  const b64 = await page.evaluate(async ({ src, size }) => {
    const img = new Image(); img.src = src; await img.decode();
    const c = document.createElement("canvas"); c.width = c.height = size;
    const x = c.getContext("2d"); x.imageSmoothingQuality = "high";
    x.drawImage(img, 16, 16, 96, 96, 0, 0, size, size);
    return c.toDataURL("image/png").split(",")[1];
  }, { src: iconSrc, size });
  writeFileSync(join(ROOT, `src/icons/${size}.png`), Buffer.from(b64, "base64"));
}
await browser.close();

console.log(`synced naturable-rules ${rulesPkg.version} · ${Object.keys(words).length} word links · 4 icons from store/source/icon-128-padded.png`);
